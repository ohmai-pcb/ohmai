#!/usr/bin/env python3
"""Rewrite cli/requirements.lock (pip --require-hashes format) from the exact pins in cli/constraints.txt.

Every distribution file PyPI publishes for a pinned version is hashed, so one lock serves every platform and
Python version in the CI matrix. Also prints each pin's Requires-Python so an unsupported pin is visible.
Network: https://pypi.org/pypi/<name>/<version>/json only.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLOOR = 10   # cli/pyproject.toml requires-python >=3.10
SRC, DST = ROOT / "cli" / "constraints.txt", ROOT / "cli" / "requirements.lock"


def main() -> int:
    out = ["# Generated by scripts/pylock.py from cli/constraints.txt; do not edit by hand.",
           "# pip install --require-hashes -r cli/requirements.lock && pip install --no-deps -e cli", ""]
    for line in SRC.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        req, _, marker = (x.strip() for x in line.partition(";"))
        m = re.fullmatch(r"([A-Za-z0-9._-]+)==([A-Za-z0-9.+!-]+)", req)
        if not m:
            print(f"pylock: not an exact pin: {line}", file=sys.stderr)
            return 1
        name, ver = m.groups()
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=60) as r:
            data = json.load(r)
        hashes = sorted({f["digests"]["sha256"] for f in data["urls"]})
        if not hashes:
            print(f"pylock: {name}=={ver} has no files on PyPI", file=sys.stderr)
            return 1
        rp = data["info"].get("requires_python") or ""
        floor = re.match(r"\s*>=\s*3\.(\d+)", rp)
        if floor and int(floor.group(1)) > FLOOR and "python_version" not in marker:
            print(f"pylock: {name}=={ver} needs Python {rp}; ohmai supports 3.{FLOOR}: add a "
                  f"python_version marker and a second pin for older Pythons", file=sys.stderr)
            return 1
        print(f"{name}=={ver}  requires-python {rp}  {len(hashes)} file(s)")
        out.append(f"{name}=={ver}" + (f" ; {marker}" if marker else "") + " \\")
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    DST.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
