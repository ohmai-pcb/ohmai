#!/usr/bin/env bash
# Restore the OhmAI toolchain (KiCad 9 CLI + a durable ohmai venv) on a shared box.
# Idempotent. One agent restores at a time: the others block on the lock below (no parallel apt).
#   scripts/restore-toolchain.sh            # check, then repair what is missing
#   source "${OHMAI_VENV:-$HOME/ohmai-venv}/env.sh"
# Env: OHMAI_VENV (default $HOME/ohmai-venv; never under /tmp), KICAD_VERSION (default 9.0.2),
#      OHMAI_LOCK (default $HOME/.cache/ohmai/toolchain.lock), OHMAI_JLCPARTS_DB (left as is).
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
VENV="${OHMAI_VENV:-$HOME/ohmai-venv}"
KV="${KICAD_VERSION:-9.0.2}"
LOCK="${OHMAI_LOCK:-$HOME/.cache/ohmai/toolchain.lock}"
case "$VENV" in /tmp/*) echo "refusing OHMAI_VENV=$VENV: /tmp does not survive on a shared box" >&2; exit 2;; esac
mkdir -p "$(dirname "$LOCK")"
exec 9>"$LOCK"
if ! flock -n 9; then
  echo "another agent is restoring the toolchain ($LOCK); waiting..." >&2
  flock 9
fi
echo "pid $$ $(date -Is) $(hostname)" >&9

sudo_() { if [ "$(id -u)" = 0 ]; then "$@"; else sudo "$@"; fi; }

# ---- KiCad 9 CLI
if ! kicad-cli version 2>/dev/null | head -1 | grep -qxF "$KV"; then
  echo "kicad-cli $KV missing; installing" >&2
  apt_kicad() { sudo_ apt-get update -o Acquire::Retries=3 && sudo_ apt-get install -y "kicad=${KV}*"; }
  if ! apt_kicad; then
    echo "apt over HTTP failed (proxy?); retrying with the HTTPS Debian mirror" >&2
    for f in /etc/apt/sources.list /etc/apt/sources.list.d/*.sources /etc/apt/sources.list.d/*.list; do
      [ -f "$f" ] && sudo_ sed -i.bak-ohmai 's#http://deb.debian.org#https://deb.debian.org#g' "$f"
    done
    apt_kicad
  fi
fi
kicad-cli version
command -v pdftotext >/dev/null || sudo_ apt-get install -y poppler-utils
command -v rsvg-convert >/dev/null || sudo_ apt-get install -y librsvg2-bin || true

# ---- durable venv
if [ ! -x "$VENV/bin/python" ]; then python3 -m venv "$VENV"; fi
"$VENV/bin/pip" install -q --upgrade pip
"$VENV/bin/pip" install -q -e "$here/cli[dev,layout]" easyeda2kicad==1.0.1
cat > "$VENV/env.sh" <<ENV
# source me: puts the durable ohmai venv first on PATH (generated by scripts/restore-toolchain.sh)
export OHMAI_VENV="$VENV"
export PATH="$VENV/bin:\$PATH"
ENV
"$VENV/bin/ohmai" --version
echo "toolchain OK. next: source $VENV/env.sh && ohmai check toolchain (in the project)"
