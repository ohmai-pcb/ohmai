"""ohmai adopt: put an existing (foreign) KiCad repo under the OhmAI checks without rewriting it.

Writes, never overwriting an existing file (an existing one gets the new content next to it as *.adopted.*):
  ohmai.yaml          schematic path, checks.na: {check: reason} for checks that do not apply yet
  expected_nets.csv   every multi-node net of the CURRENT KiCad netlist, unlabeled ones included. This is a
                      regression baseline, not verified intent: review rows against datasheets (pin-map) and the
                      generator (gen-netlist, checks.gen_netlist.intent) before trusting it.
"""

from __future__ import annotations

import csv
import io
from pathlib import Path

import yaml

from ohmai.netlist import base

DEFAULT_NA = {
    "commits": "adopted repo: its history predates OhmAI trailers (set git.trailer_required_since to enforce from now on)",
    "toolchain": "adopted repo: no ohmai.lock yet (run `ohmai lock` to start pinning)",
    "review:requirements": "adopted repo: requirements were not written under OhmAI",
}


def find_root_schematic(root: Path) -> Path:
    pros = [p for p in root.rglob("*.kicad_pro") if ".git" not in p.parts and "out" not in p.parts]
    cands = [p.with_suffix(".kicad_sch") for p in pros if p.with_suffix(".kicad_sch").is_file()]
    if len(cands) != 1:
        raise SystemExit(f"ohmai adopt: found {len(cands)} root schematic(s) next to a .kicad_pro "
                         f"({', '.join(str(c.relative_to(root)) for c in cands) or 'none'}); pass --schematic")
    return cands[0]


def expected_rows(nl) -> str:
    buf = io.StringIO()
    buf.write("# Generated by `ohmai adopt` from the current KiCad netlist: a regression baseline, NOT verified\n"
              "# intent. Check each row against datasheets / the generator, then delete this comment.\n")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["net", "nodes"])
    nc = []
    for name in sorted(nl.nets, key=base):
        nodes = sorted(nl.nets[name])
        if len(nodes) < 2:
            if base(name).startswith("unconnected-("):
                nc += nodes
            continue
        w.writerow([base(name), *nodes])
    if nc:
        w.writerow(["NC", *nc])
    return buf.getvalue()


def _write(path: Path, text: str, log: list[str]) -> None:
    if path.exists():
        alt = path.with_name(path.stem + ".adopted" + path.suffix)
        if alt.exists():
            raise SystemExit(f"ohmai adopt: {path.name} and {alt.name} both exist; move one away first")
        alt.write_text(text, encoding="utf-8")
        log.append(f"{path.name} exists: left untouched, wrote {alt.name} (merge by hand)")
    else:
        path.write_text(text, encoding="utf-8")
        log.append(f"wrote {path.name}")


def adopt(root: Path, schematic: Path | None = None, na: dict[str, str] | None = None,
          netlist: Path | None = None) -> list[str]:
    from ohmai import kicad
    from ohmai.netlist import load

    root = root.resolve()
    sch = (root / schematic).resolve() if schematic else find_root_schematic(root)
    rel = sch.relative_to(root).as_posix()
    cfg = {"project": root.name, "hardware": {"schematic": rel},
           "checks": {"na": {**DEFAULT_NA, **(na or {})}, "cross_sheet_strict": True,
                      "readability": {"labels": "rail-and-label"}}}
    try:
        from ohmai.resources import template_dir

        tk = (yaml.safe_load((template_dir() / "ohmai.yaml").read_text(encoding="utf-8")) or {}).get("kicad")
    except Exception:  # template not shipped: leave kicad pins to `ohmai kicad-libs`
        tk = None
    if tk:
        cfg["kicad"] = {k: tk[k] for k in ("libraries", "app") if k in tk}
    gen = sch.parent / "gen" / "layout"
    if not gen.is_dir():
        cfg["checks"]["na"].setdefault(
            "gen-netlist", "no OhmAI generator; set checks.gen_netlist.intent to the repo generator's ref.pin,net CSV")
    log: list[str] = []
    _write(root / "ohmai.yaml", "# Written by `ohmai adopt`. N/A entries are owner-visible: each needs a reason.\n"
           + yaml.safe_dump(cfg, sort_keys=False), log)
    if netlist is None:
        out = root / "out"
        out.mkdir(exist_ok=True)
        netlist = out / "netlist.net"
        r = kicad.run(["sch", "export", "netlist", "--format", "kicadsexpr", "-o", str(netlist), str(sch)],
                      log=out / "netlist.log")
        if kicad.load_failed(r) or not netlist.exists():
            raise SystemExit("ohmai adopt: netlist export failed (see out/netlist.log)")
    nl = load(netlist)
    if not nl.comps:
        raise SystemExit("ohmai adopt: the netlist has 0 components (schematic did not load?)")
    _write(root / "expected_nets.csv", expected_rows(nl), log)
    log.append(f"{len(nl.comps)} parts, {sum(1 for n in nl.nets.values() if len(n) > 1)} nets baselined; "
               f"N/A: {', '.join(sorted(cfg['checks']['na']))}")
    log.append("next: ohmai check schematic (then ohmai check schematic --sheet <name> per sheet)")
    return log
